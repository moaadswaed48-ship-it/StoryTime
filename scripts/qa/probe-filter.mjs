import { chromium } from 'playwright'
import { ensureServer, BASE } from './serve.mjs'
const server = await ensureServer()
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
p.on('pageerror', (e) => console.error('pageerror', e.message))
await p.goto(BASE + '?qa=1', { waitUntil: 'networkidle' }); await p.waitForTimeout(1800)
await p.evaluate(() => { const el = document.querySelector('.shelf-view'); window.__st.lenis.scrollTo(el.getBoundingClientRect().top + window.scrollY - 110, { immediate: true, force: true }) })
await p.waitForTimeout(600); await p.evaluate(() => window.__st.shelf.settleNow()); await p.waitForTimeout(300)
await p.getByRole('button', { name: 'Ages 3–5', exact: true }).click(); await p.waitForTimeout(2500)
console.log('after chip:', await p.evaluate(() => ({ hidden: window.__st.shelf.hidden(), phase: window.__st.shelf.phase(), count: document.querySelector('[aria-live]').textContent })))
await p.screenshot({ path: 'qa/out/1440-filtered.png' })
await p.getByRole('button', { name: 'Ages 3–5', exact: true }).click(); await p.waitForTimeout(2500)
await p.evaluate(() => window.__st.shelf.settleNow())
await p.evaluate(() => window.__st.shelf.spin('the-moon-who-lost-her-hat')); await p.waitForTimeout(900)
console.log('spinning:', await p.evaluate(() => window.__st.shelf.phase()))
await p.screenshot({ path: 'qa/out/1440-spin.png' })
await p.waitForTimeout(4000)
console.log('after spin:', await p.evaluate(() => ({ phase: window.__st.shelf.phase(), dialog: document.querySelector('dialog')?.open })))
await p.keyboard.press('Escape'); await p.waitForTimeout(800)
await b.close(); server.stop()
